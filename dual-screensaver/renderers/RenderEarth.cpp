#include "framework.h"
#include "ScreensaverRegistry.h"
#include "ScreenData.h"
#include "Settings.h"
#include "../settings/EarthSettings.h"
#include "GlyphAtlas.h"
#include <math.h>
#include <vector>

struct EarthState {
    float angle = 0.0f;
    std::vector<char> b;
    GlyphAtlas atlas;
    HFONT atlasFont = NULL;
    CenteredTextBlock layout;
    PixelCanvas canvas;
};

void RenderEarth(HDC memDC, ScreenData* data, int width, int height, const RECT& rect) {
    auto& state = data->GetCustomState<EarthState>(3);

    SelectObject(memDC, data->hFont);
    TEXTMETRICA tm;
    GetTextMetricsA(memDC, &tm);

    int W = width / tm.tmAveCharWidth;
    int H = height / tm.tmHeight;
    if (W <= 0) W = 1;
    if (H <= 0) H = 1;

    std::vector<char>& b = state.b;
    b.assign(W * H, ' ');

    float R_x = min(W / 2.0f, H * 1.0f) * 0.9f;
    float R_y = R_x * 0.5f;

    const char* earth_map[34] = {
        "............................................................................................................................................",
        "............................................................................................................................................",
        "..................................+++++++..+++++++++++++++++++..............................................................................",
        "......................+.+++++..+.+.+++++........++++++++++++++.............................+..........++++++++++++++..+.....++..............",
        "......++++++++++++++++++++++++++++++++..++++.....++++++++++.................++++++++.....+++++++++++++++++++++++++++++++++++++++++++++++++++",
        "......+++++++++++++++++++++++++++++.....++++......++++...................++++.+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++.",
        "........++.......+++++++++++++++++......++++++......................+....++++..++++++++++++++++++++++++++++++++++++++++++++++......++.......",
        "....................++++++++++++++++++.+++++++++....................++..++++++++++++++++++++++++++++++++++++++++++++++++++++.......+........",
        "......................+++++++++++++++++++++++........................+++++++++++++++++++++++++++++++++++++++++++++++++++++++................",
        "......................+++++++++++++++++++++........................++++...+.+++++....++++.+++++++++++++++++++++++++++++++...................",
        "......................+++++++++++++++++++..........................+++........+..++++++++..+++++++++++++++++++++++++...+....+...............",
        ".........................++++++++++++++............................+++++++++..+....++++++++++++++++++++++++++++++++++.......................",
        "..........................++++++......+..........................++++++++++++++++++++++++++++++++++++++++++++++++++++.......................",
        ".............................+++................................++++++++++++++++++++.++++++++....+++++++++++++++++..........................",
        "...............................++.++............................+++++++++++++++++++++.+++++.......++++.....+++++............................",
        "....................................++..........................+++++++++++++++++++++++++..........++.......+.++............................",
        "........................................+++++++..................++++++++++++++++++++++++...................................................",
        ".......................................+++++++++++........................++++++++++++++.....................+...+++........................",
        ".......................................++++++++++++++++...................++++++++++++.......................++..++........++...............",
        ".......................................+++++++++++++++++...................++++++++++.......................................++..............",
        "........................................+++++++++++++++....................+++++++++++..................................+++..+..............",
        "..........................................+++++++++++++....................+++++++++...++............................++++++++++.............",
        "...........................................+++++++++........................++++++++...+..........................+++++++++++++++...........",
        "..........................................+++++++++.........................++++++................................+++++++++++++++...........",
        "..........................................+++++++............................+++...................................+++....+++++++...........",
        "..........................................++++................................................................................+.............",
        ".........................................++++...............................................................................................",
        ".........................................+++................................................................................................",
        "............................................................................................................................................",
        "............................................................................................................................................",
        "............................................................................................................................................",
        "............................................++.....................................+.++++++++++++..+++++++++++++++++++++++++++++++++........",
        "....................+++++++...++++++++++++++++.................+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++......",
        "..........+++++++++++++++++++++++++++++++..........+....+++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++......."
    };

    for (int y = 0; y < H; y++) {
        for (int x = 0; x < W; x++) {
            float cx = (x - W / 2.0f);
            float cy = (y - H / 2.0f);

            float nx = cx / R_x;
            float ny = cy / R_y;
            float d2 = nx * nx + ny * ny;

            if (d2 <= 1.0f) {
                float nz = sqrt(1.0f - d2);
                float lat = asin(ny);
                float lon = atan2(nx, nz) + state.angle;

                float u = (lon + 3.14159f) / (2.0f * 3.14159f);
                float v = (lat + 3.14159f / 2.0f) / 3.14159f;

                u = u - floor(u);
                if (v < 0.0f) v = 0.0f;
                if (v > 0.999f) v = 0.999f;

                int map_x = (int)(u * 140) % 140;
                int map_y = (int)(v * 34) % 34;

                b[y * W + x] = earth_map[map_y][map_x];
            }
        }
    }

    if (state.atlasFont != data->hFont) {
        state.atlas.Build(memDC, data->hFont, L' ', 95);
        state.atlasFont = data->hFont;
    }
    state.layout.Update(memDC, rect, W, H);
    state.canvas.Begin(width, height);

    const int charW = tm.tmAveCharWidth;
    const int charH = tm.tmHeight;
    for (int y = 0; y < H; y++) {
        for (int x = 0; x < W; x++) {
            char c = b[y * W + x];
            if (c == ' ') continue;
            state.atlas.Draw(state.canvas, state.layout.x + x * charW, state.layout.y + y * charH, c - ' ', 0x00FF00);
        }
    }
    state.canvas.End(memDC, rect.left, rect.top);

    state.angle += g_EarthSpeed;
}

REGISTER_SCREENSAVER(
    3,
    L"Earth",
    "earth",
    { "earth" },
    WRAP_LEGACY(RenderEarth),
    GetEarthSettings()
);
